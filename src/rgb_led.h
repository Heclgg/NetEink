/**
 * 板载 WS2812 指示灯：连续呼吸灯引擎（非阻塞）
 * ----------------------------------------------------------------------------
 *   亮度 = 基色 x 峰值 x [下限 + (1-下限) x (1-cos(2*PI*t/T))/2]
 *
 * - 升余弦两端导数为 0（暗->亮->暗 没有折点），比三角波更像「吸气/呼气」；
 * - 下限不为 0，最暗时仍留一点余光，不会像在开关；
 * - 每种状态有自己的颜色 / 周期 / 下限；切状态时相位归零 + 输出缓动，
 *   不会「啪」地变亮或变色；
 * - rgbTick() 内部按 20ms 限流，可以放心地在主循环、WiFi 等待、刷屏等待
 *   这些地方随手调用。
 * ==========================================================================*/
#pragma once
#include <stdint.h>

enum RgbMode : uint8_t {
    RGB_OFF = 0,   // 熄灭（待机）
    RGB_WAIT,      // 蓝色慢呼吸：联网 / 对时 / 取天气
    RGB_WORK,      // 红色呼吸：墨水屏刷新中
    RGB_CONFIG,    // 绿色慢呼吸：配网等待手机提交
    RGB_OK,        // 绿色浅呼吸（接近常亮）：本轮刷新完成
};

/** 绑定引脚与亮度峰值。peak 取 0-255，是呼吸最高点的通道值，越小越暗。 */
void rgbBegin(uint8_t pin, uint8_t peak = 96);

/** 切换指示灯状态；同一状态重复调用不会打断当前呼吸相位。 */
void rgbSetMode(RgbMode mode);

/** 熄灭（带约 200ms 的淡出，不是硬切）。 */
void rgbOff();

/** 推进呼吸波形；内部按 20ms 限流，重复调用无副作用。 */
void rgbTick();
