/**
 * 板载 WS2812 指示灯：闪三下就熄（非阻塞）
 * ----------------------------------------------------------------------------
 *   亮度 = 基色 x 峰值 x [下限 + (1-下限) x (1-cos(2*PI*t/T))/2]
 *
 * - 升余弦两端导数为 0（暗->亮->暗 没有折点），比硬开关柔和；
 * - 每个状态自带「闪几次」，闪完自动淡出熄灭，不会一直亮着；
 * - 每种状态有自己的颜色 / 周期 / 下限；切状态时相位归零 + 输出缓动，
 *   不会「啪」地变亮或变色；
 * - rgbTick() 内部按 20ms 限流，可以放心地在主循环、WiFi 等待、刷屏等待
 *   这些地方随手调用。
 *
 * 只保留两个「需要你看一眼」的提示（其余一律不亮，见 rgb_led.cpp）：
 *   RGB_OK    绿色闪三下 —— 图片已经刷到屏上（扫码传图 / 长按 KEY2 重放）
 *   RGB_PROV  橙色闪三下 —— 配网二维码已就绪，等手机提交凭据
 * 刷屏中、联网、对时、取天气、天气页定时刷新：都不亮。
 *
 * 总开关 NETEINK_LED（platformio.ini 里置 0）：
 *   置 0 时四个接口都变成空函数，rgbBegin 只把数据脚拉低（WS2812 的空闲电平），
 *   不初始化 RMT、不发送任何帧——灯永远不亮。调用点不用改。
 * ==========================================================================*/
#pragma once
#include <stdint.h>

#ifndef NETEINK_LED
#define NETEINK_LED 1       // 默认开；平台的 build_flags 里会置 0
#endif

enum RgbMode : uint8_t {
    RGB_OFF = 0, // 熄灭
    RGB_OK, // 绿色闪三下：图片刚上屏
    RGB_PROV, // 橙色闪三下：配网二维码刚就绪
};

/** 绑定引脚与亮度峰值。peak 取 0-255，是呼吸最高点的通道值，越小越暗。 */
void rgbBegin(uint8_t pin, uint8_t peak = 96);

/** 切换指示灯状态；同一状态重复调用不会打断当前呼吸相位。 */
void rgbSetMode(RgbMode mode);

/** 熄灭（带约 200ms 的淡出，不是硬切）。 */
void rgbOff();

/** 推进呼吸波形；内部按 20ms 限流，重复调用无副作用。 */
void rgbTick();
